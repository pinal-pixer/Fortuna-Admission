<script>
document.addEventListener("DOMContentLoaded", function () {

    const form = document.querySelector(".mba-simple-consultation-form");
    if (!form) return;

    const sharedTextFields = ["first_name", "last_name", "email", "phone", "country", "hear_about_us"];
    const redirectTo = "/mba/free-consultation-step-2/";
    const ajaxUrl = "<?php echo esc_url(admin_url('admin-ajax.php')); ?>";
    const tokenField = form.querySelector('input[name="g-recaptcha-response"]');

    // Show SMS consent when a phone number is entered; auto-check the box so the
    // user opts in by default (matching MIM/UG behaviour).
    const phoneInput   = document.getElementById("phone");
    const phoneField   = window.faPhoneField
        ? window.faPhoneField.init({
            input: phoneInput,
            hidden: form.querySelector('input[name="phone"]'),
            countrySelect: document.getElementById("country"),
            ajaxUrl: ajaxUrl
        })
        : null;

    function syncPhone() {
        if (phoneField) {
            phoneField.sync();
            return;
        }
        const hidden = form.querySelector('input[name="phone"]');
        if (hidden && phoneInput) hidden.value = phoneInput.value.trim();
    }
    const consentCb    = document.getElementById("mba_simple_sms_consent");
    const consentGroup = document.getElementById("mba_simple_sms_consent_group");

    if (phoneInput && consentCb && consentGroup) {
        phoneInput.addEventListener("input", function () {
            if (phoneInput.value.trim().length > 0) {
                consentGroup.style.display = "";
                consentCb.checked = true;
            } else {
                consentGroup.style.display = "none";
                consentCb.checked = false;
            }
        });
    }

    // Build the Form 2 URL with shared field values as query params so the next page
    // can render them server-side into the input `value` attributes — instant fill.
    function buildRedirectUrl() {
        const params = new URLSearchParams();

        sharedTextFields.forEach(function (fieldName) {
            const f = form.querySelector('[name="' + fieldName + '"]');
            if (f && f.value) {
                params.set(fieldName, f.value);
            }
        });

        // Persist SMS opt-in choice — checkbox value only sends if checked, so we
        // read `checked` directly and pass "Yes"/"No" so Form 2 can restore it.
        if (consentCb) {
            params.set("sms_consent", consentCb.checked ? "Yes" : "No");
        }

        const qs = params.toString();
        return qs ? redirectTo + "?" + qs : redirectTo;
    }

    // Persist resume (if any) into sessionStorage so Form 2 can restore it,
    // then continue to Form 2.
    function persistResumeAndRedirect(targetUrl) {
        const resumeInput = form.querySelector('input[name="resume"]');
        const file = resumeInput && resumeInput.files && resumeInput.files[0];

        if (!file) {
            sessionStorage.removeItem("mba_resume");
            window.location.href = targetUrl;
            return;
        }

        const reader = new FileReader();

        reader.onload = function () {
            try {
                sessionStorage.setItem("mba_resume", JSON.stringify({
                    name: file.name,
                    type: file.type,
                    data: reader.result
                }));
            } catch (err) {
                sessionStorage.removeItem("mba_resume");
            }
            window.location.href = targetUrl;
        };

        reader.onerror = function () {
            window.location.href = targetUrl;
        };

        reader.readAsDataURL(file);
    }

    // Send Form 1 data to the server. We wait for the response (with a hard
    // timeout) before redirecting so Step 1 is always recorded. The resume
    // file is intentionally excluded from this payload — it travels to Step 2
    // via sessionStorage and is uploaded on the Step 2 submit. This avoids the
    // browser's 64 KB `keepalive` body cap that was silently dropping Step 1
    // requests with resumes attached.
    function sendPartialSubmission() {
        const fd = new FormData();

        // Copy text fields only — skip the file input.
        const textFields = [
            "action",
            "mba_simple_consultation_nonce_field",
            "_wp_http_referer",
            "g-recaptcha-response",
            "completed_full_form",
            "code",
            "first_name",
            "last_name",
            "email",
            "phone",
            "linkedin",
            "country",
            "hear_about_us",
            "additional_information"
        ];

        textFields.forEach(function (name) {
            const el = form.querySelector('[name="' + name + '"]');
            if (!el) return;
            if (el.type === "checkbox") {
                if (el.checked) fd.set(name, el.value || "on");
            } else {
                fd.set(name, el.value || "");
            }
        });

        if (consentCb) {
            fd.set("sms_consent", consentCb.checked ? "Yes" : "No");
        }

        const controller = (typeof AbortController !== "undefined") ? new AbortController() : null;
        const timeoutId = setTimeout(function () {
            if (controller) controller.abort();
        }, 3500);

        return fetch(ajaxUrl, {
            method: "POST",
            body: fd,
            credentials: "same-origin",
            signal: controller ? controller.signal : undefined
        }).then(function (res) {
            clearTimeout(timeoutId);
            if (!res.ok) throw new Error("HTTP " + res.status);
            return res.json().catch(function () { return { success: true }; });
        }).catch(function (err) {
            clearTimeout(timeoutId);
            return { success: false, error: err && err.message ? err.message : "network" };
        });
    }

    function resetSubmitButton() {
        const btn = form.querySelector('button[type="submit"]');
        if (btn) {
            btn.disabled = false;
            btn.textContent = "Next";
        }
    }

    function showStep1Error(message) {
        resetSubmitButton();
        alert(message || "We couldn't save your details. Please check your connection and try again.");
    }

    function submitAndRedirect(token) {
        if (tokenField) tokenField.value = token || "";

        sendPartialSubmission().then(function (result) {
            if (!result || result.success === false) {
                showStep1Error();
                return;
            }
            persistResumeAndRedirect(buildRedirectUrl());
        });
    }

    form.addEventListener("submit", function (e) {
        e.preventDefault();

        if (!form.checkValidity()) {
            form.reportValidity();
            return;
        }

        syncPhone();

        const btn = form.querySelector('button[type="submit"]');

        if (btn) {
            btn.disabled    = true;
            btn.textContent = "Please wait...";
        }

        window.dataLayer = window.dataLayer || [];
        window.dataLayer.push({
            event: "MBASimpleFormSubmit"
        });

        // Resolve reCAPTCHA token before submitting; fall back after 2.5s so a
        // slow/failed grecaptcha never blocks the user forever.
        let submitted = false;
        function go(token) {
            if (submitted) return;
            submitted = true;
            submitAndRedirect(token);
        }

        if (typeof grecaptcha !== "undefined") {
            try {
                grecaptcha.ready(function () {
                    grecaptcha.execute("6LevnXYtAAAAAMJD8mj2aeDja_yK6R20db50KgpD", {
                        action: "mba_simple_consultation"
                    }).then(function (token) {
                        go(token || "");
                    }).catch(function () { go(""); });
                });
                setTimeout(function () { go(""); }, 2500);
            } catch (err) {
                go("");
            }
        } else {
            go("");
        }
    });
});
</script>